def paired_ci(df, arm, base, metric, cl_col, nb=NB, seed=SEED):
    a = df.pivot_table(index="tid", columns="arm", values=metric, aggfunc="first")
    if arm not in a or base not in a:
        return None
    ok = a[arm].notna() & a[base].notna()
    dv = (a.loc[ok, arm].astype(float) - a.loc[ok, base].astype(float))
    meta = df.drop_duplicates("tid").set_index("tid")
    out = {"est": float(dv.mean()), "n": int(len(dv))}
    for nm, cl in (("task", None), ("fact", meta.loc[dv.index, "iid"].to_numpy()),
                   ("repo", meta.loc[dv.index, cl_col].to_numpy() if cl_col else None)):
        if nm != "task" and cl is None:
            continue
        rng = np.random.default_rng(seed)
        x = dv.to_numpy()
        if cl is None:
            bs = x[rng.integers(0, len(x), (nb, len(x)))].mean(1)
        else:
            g = pd.Series(x).groupby(cl)
            s, n = g.sum().to_numpy(), g.size().to_numpy()
            idx = rng.integers(0, len(s), (nb, len(s)))
            bs = s[idx].sum(1) / n[idx].sum(1)
        out[nm] = np.percentile(bs, [2.5, 97.5]).tolist()
    return out


def rate_ci(df, arm, metric, nb=NB, seed=SEED):
    s = df[df.arm == arm]
    x = s[metric].astype(float).to_numpy()
    g = pd.Series(x).groupby(s.iid.to_numpy())
    S, N = g.sum().to_numpy(), g.size().to_numpy()
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(S), (nb, len(S)))
    return float(x.mean()), np.percentile(S[idx].sum(1) / N[idx].sum(1), [2.5, 97.5]).tolist()


