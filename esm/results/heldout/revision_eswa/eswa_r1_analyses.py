def fmt(x):
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.1f}"


def per_fact_rates(d):
    """per fact: (wrong reads, reads, wrong reads present, reads present)."""
    nn = ~np.fromiter((NONE_AT[i][t] for i, t in zip(d.iid.to_numpy(), d.t.to_numpy())), bool, len(d))
