def tools_from(rec, store):
    nf = rec.iid.nunique()
    dr = rec[rec.n_der > 0]
    tl = sum(len((store.get((i, int(t))) or {}).get("trace") or []) for i, t in zip(dr.iid, dr.t))
    miss = sum(1 for i, t in zip(dr.iid, dr.t) if (i, int(t)) not in store)
    return rec.guard_io.sum() / nf, tl / nf, miss


def sweep(rows, esm_key, label):
    e = rows[esm_key]
    L.append(f"\n### {label}\n")
    L.append("| policy | facts | LLM tokens/fact | tool executions/fact | w* (tokens per tool execution) | cost ratio policy/ESM at w = 0 / 10 / 50 / 200 |")
    L.append("|---|---|---|---|---|---|")
    res = {}
    for p, r in rows.items():
        ee = r.get("esm", e)
        dt, dx = r["tok"] - ee["tok"], ee["tools"] - r["tools"]
        if p == esm_key:
            ws = None
        elif dx > 0:
            ws = dt / dx           # ESM cheaper iff w < ws (dt > 0) ; if dt <= 0 never cheaper
        elif dx < 0:
            ws = -np.inf if dt >= 0 else dt / dx
        else:
            ws = np.nan
        ratios = [(r["tok"] + w * r["tools"]) / (ee["tok"] + w * ee["tools"]) for w in (0, 10, 50, 200)]
        res[p] = {**r, "w_star": ws, "ratios": ratios}
        wtxt = "–" if ws is None else ("ESM never cheaper" if (dx > 0 and dt <= 0) else
                                       ("ESM cheaper at every w" if dx <= 0 and dt >= 0 else f"{ws:.1f}"))
        extra = f" (LLM calls {r['llm_calls']:.1f}, est. serial LLM min {r['est_llm_min']:.1f})" if "est_llm_min" in r else ""
