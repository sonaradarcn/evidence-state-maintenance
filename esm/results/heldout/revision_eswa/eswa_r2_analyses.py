"""ESWA round-2 reviewer analysis (zero LLM, zero GPU). Run from the project root, AFTER eswa_r1_analyses.py:
    python esm/results/heldout/revision_eswa/eswa_r2_analyses.py
Outputs eswa_r2_analyses.md / .json next to this file.

Repository-cluster sensitivity of every paired code contrast of main Table 7 (downstream task study). The intervals
themselves are computed by eswa_r1_analyses.py section C (paired_ci: task-level, fact-clustered and repository-clustered
bootstrap, B = 2000, seed 1); this script collects them, adds the cluster structure (facts per repository) from the task
records, and checks for each contrast whether the 'interval excludes zero' verdict (Section 6.3 rule) is the same under
fact and repository clustering. Lakes: only two lakes, so no lake-level clustering is possible.
"""
import json
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
E1 = json.loads((HERE / "eswa_r1_analyses.json").read_text(encoding="utf-8"))["C"]

code = pd.read_parquet(ROOT / "esm/results/e2e/task_outcomes.parquet")
code["repo"] = code.iid.str.split(":").str[0]
fr = code.drop_duplicates("iid").groupby("repo").size()
lake = pd.read_parquet(ROOT / "esm/results/e2e_lake/task_outcomes.parquet")

OUT = {"facts_per_repo": fr.to_dict(), "n_facts_code": int(code.iid.nunique()), "n_repos_code": int(fr.size),
       "n_tasks_code": int(code.tid.nunique()), "n_facts_lake": int(lake.iid.nunique()), "contrasts": {}}
L = ["# ESWA round 2 — repository-cluster sensitivity of Table 7 (generated by eswa_r2_analyses.py; zero LLM)\n",
     f"Code: {OUT['n_tasks_code']} tasks, {OUT['n_facts_code']} facts, {OUT['n_repos_code']} repositories; facts per "
     f"repository min {fr.min()}, median {fr.median():g}, max {fr.max()} ({dict(sorted(fr.items()))}).",
     f"Lakes: {OUT['n_facts_lake']} facts in 2 lakes (no lake-level clustering possible).\n",
     "Intervals from eswa_r1_analyses.json section C (B = 2000, seed 1). 'zero?' = interval includes zero "
     "(an endpoint printed as ±0.0 counts as including zero only if it is exactly 0 or of the other sign).\n",
     "| prompt | contrast | metric | Δ | task CI | fact CI (primary) | repo CI | fact incl. 0 | repo incl. 0 | same verdict |",
     "|---|---|---|---|---|---|---|---|---|---|"]


def incl0(c):
    return c[0] <= 0 <= c[1]


changed = 0
for key, r in E1.items():
    env, prompt, contrast, metric = key.split("|")
    if env != "code":
        continue
    k = 1 / 1000 if metric == "tok" else 100
    if all(abs(v) < 1e-12 for v in r["fact"] + r["repo"]) and abs(r["est"]) < 1e-12:
        same, fz, rz = True, "identical arms", "identical arms"
    else:
        fz, rz = incl0(r["fact"]), incl0(r["repo"])
        same = fz == rz
    changed += not same
    OUT["contrasts"][key] = {**r, "fact_incl0": fz, "repo_incl0": rz, "same": same}
    f = lambda c: f"[{c[0] * k:+.1f}, {c[1] * k:+.1f}]"   # noqa: E731
    L.append(f"| {prompt} | {contrast.replace('-', ' − ', 1)} | {metric} | {r['est'] * k:+.1f} | {f(r['task'])} | "
             f"{f(r['fact'])} | {f(r['repo'])} | {fz} | {rz} | {'yes' if same else 'NO'} |")
OUT["verdict_changes"] = changed
L.append(f"\nContrasts whose zero-inclusion verdict differs between fact and repository clustering: {changed}.")
(HERE / "eswa_r2_analyses.md").write_text("\n".join(L) + "\n", encoding="utf-8")
(HERE / "eswa_r2_analyses.json").write_text(json.dumps(OUT, indent=1, default=float), encoding="utf-8")
print("\n".join(L))
