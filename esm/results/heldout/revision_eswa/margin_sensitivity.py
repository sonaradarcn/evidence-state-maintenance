"""ESWA revision, item B2 / A5: non-inferiority margin sensitivity (zero LLM, zero GPU).

Delta = ESM - B in served-wrong (pp); positive Delta = ESM worse.  Same procedure as revision_r1/item2_noninferiority.py
and revision_r1_runs/analyze.py (B.3):
  * paired_stats() from revision_r1/r1_common.py (seed 1, B = 2000; fact bootstrap and repository-cluster bootstrap);
  * non-inferiority (NI) at margin m: one-sided 95 % upper bound (= 95th bootstrap percentile) < m;
  * equivalence (EQ, TOST at alpha = 0.05 per side): the 90 % two-sided interval lies inside (-m, +m).
Margins: 0.5, 1.0, 1.5, 2.0 pp.  Sets:
  * S160 (result files: H150), every commit, from esm/results/heldout/records.parquet (via r1_common.pf);
  * NAT100, every commit: baselines from revision_r1_runs/records_r1.parquet (experiment B), ESM from the main
    frozen run (records.parquet) restricted to the same facts -- as revision_r1_runs/analyze.py.
CERT-V0H (result files: CERT-v0) is compared on its static facts only (133 in S160, 92 in NAT100), ESM on the same facts.
Outputs (this folder): margin_sensitivity.md, margin_sensitivity.json, margin_sensitivity_table.tex (Supp. Table S8).
Run: python esm/results/heldout/revision_eswa/margin_sensitivity.py   (from the project root)
"""
import json, sys
from pathlib import Path

HERE_ESWA = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE_ESWA.parent / "revision_r1"))
from r1_common import *  # noqa: F401,F403  (FACTS, FX, H150, FROZEN, pf, paired_stats, M, pd, np, DATA_DIR)

MARGINS = (0.005, 0.010, 0.015, 0.020)
BASELINES = (("CERT-ZS", "CERT-ZS"), ("CERT-v0", "CERT-V0H"), ("LLMDIFF", "LLMDIFF"))
NAT100 = set(json.loads((DATA_DIR / "sub_NAT100.json").read_text()))
R1 = pd.read_parquet(HERE_ESWA.parent / "revision_r1_runs" / "records_r1.parquet")


def pf_nat(policy):
    d = R1[(R1.experiment == "B") & (R1.policy == policy) & (R1.schedule == "every")].copy()
    f = M.per_fact(d, FACTS)
    return f


OUT, rows = {}, []
esm_all = pf(FROZEN)
for setname in ("S160", "NAT100"):
    for key, lab in BASELINES:
        if setname == "S160":
            a, b, ids = esm_all, pf(key), set(H150)
        else:
            a, b, ids = esm_all, pf_nat(key), set(NAT100)
        p = paired_stats(a, b, ids)
        for unit, q in (("fact", p["fact"]), ("repo", p["clu"])):
            lo95, hi95, lo90, hi90 = q
            ni = [bool(hi90 < m) for m in MARGINS]
            eq = [bool(lo90 > -m and hi90 < m) for m in MARGINS]
            r = {"set": setname, "baseline": lab, "unit": unit, "n": p["n"], "esm": p["wa"], "base": p["wb"], "d": p["d"],
                 "ci90": [lo90, hi90], "ub": hi90, "ni": ni, "eq": eq,
                 "smallest_ni_margin": max(hi90, 0.0), "smallest_eq_margin": max(-lo90, hi90)}
            OUT[f"{setname}|{lab}|{unit}"] = r
            rows.append(r)

yn = lambda v: "yes" if v else "no"
L = ["# Non-inferiority margin sensitivity (generated by margin_sensitivity.py)\n",
     "Delta = ESM - baseline, served-wrong pp, every commit; positive = ESM worse. NI at m: one-sided 95 % upper bound < m. "
     "EQ (TOST): 90 % CI inside (-m, +m). Bootstrap B = 2000, seed 1 (as revision_r1 item 2).\n",
     "| set | baseline | unit | facts | ESM % / B % | Delta | 90 % CI | one-sided 95 % UB | NI at 0.5 / 1.0 / 1.5 / 2.0 pp | EQ at 0.5 / 1.0 / 1.5 / 2.0 pp |",
     "|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    L.append(f"| {r['set']} | {r['baseline']} | {r['unit']} | {r['n']} | {100*r['esm']:.1f} / {100*r['base']:.1f} | {100*r['d']:+.2f} "
             f"| [{100*r['ci90'][0]:+.2f}, {100*r['ci90'][1]:+.2f}] | {100*r['ub']:+.2f} | {' / '.join(map(yn, r['ni']))} "
             f"| {' / '.join(map(yn, r['eq']))} |")
(HERE_ESWA / "margin_sensitivity.md").write_text("\n".join(L) + "\n", encoding="utf-8")
(HERE_ESWA / "margin_sensitivity.json").write_text(json.dumps(OUT, indent=1, default=float), encoding="utf-8")

# LaTeX rows for Supplementary Table S8
mk = lambda v: r"\checkmark" if v else r"--"
T = []
prev = None
for r in rows:
    if r["set"] != prev:
        if prev is not None:
            T.append(r"\midrule")
        T.append(r"\multicolumn{15}{l}{\emph{" + ("S160 (160 facts; change-enriched)" if r["set"] == "S160" else "NAT100 (100 natural facts, uniform random sample)") + r"}} \\")
        prev = r["set"]
    lab = r"\pol{" + r["baseline"].lower() + "}"
    unit = "facts" if r["unit"] == "fact" else "repos"
    T.append(f"{lab} & {unit} & {r['n']} & {100*r['esm']:.1f} / {100*r['base']:.1f} & ${100*r['d']:+.2f}$ & "
             f"[${100*r['ci90'][0]:+.2f}$, ${100*r['ci90'][1]:+.2f}$] & ${100*r['ub']:+.2f}$ & "
             + " & ".join(mk(v) for v in r["ni"]) + " & " + " & ".join(mk(v) for v in r["eq"]) + r" \\")
HEAD = [r"\begin{tabular}{llrlllrcccccccc}", r"\toprule",
        r" & & & & & & & \multicolumn{4}{c}{NI at $\delta$ (pp)} & \multicolumn{4}{c}{EQ at $\pm\delta$ (pp)} \\",
        r"\cmidrule(lr){8-11}\cmidrule(lr){12-15}",
        r"Baseline & Unit & Facts & \ESM\,/\,B\,\% & $\Delta$ & 90\,\% CI & UB & 0.5 & 1.0 & 1.5 & 2.0 & 0.5 & 1.0 & 1.5 & 2.0 \\",
        r"\midrule"]
TAIL = [r"\bottomrule", r"\end{tabular}"]
(HERE_ESWA / "margin_sensitivity_table.tex").write_text("\n".join(HEAD + T + TAIL) + "\n", encoding="utf-8")
print("\n".join(L))
