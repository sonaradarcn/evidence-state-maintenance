"""Cost comparisons with and without the one-time certificate construction (zero LLM, zero GPU).
Tokens per fact of CERT-ZS / CERT-v0h in every paper table already include construction (r1_common.pf / analyze.load add
certs.jsonl tokens); LLM calls and estimated minutes in item7 §7c did not. This script reports, per policy and set:
steady-state (maintenance only) and construction-inclusive tokens, LLM calls and estimated serial minutes, and the token /
call ratio policy / ESM in both accountings with fact and repository-cluster 95 % CIs.
Construction calls per fact come from cert_calls.py (offline replay of esm.certs, every call a cache hit, tokens checked).
Output: cost_construction.md, cost_construction.json (this folder)."""
import json, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "revision_r1"))
from r1_common import *                    # noqa
from esm.maintain import read_shards
OUTDIR = Path(__file__).resolve().parent

CC = json.loads((OUTDIR / "cert_calls.json").read_text())["per_fact"]
SIMR1, SIM = DATA_DIR / "sim_r1", DATA_DIR / "sim"
NAT100 = set(json.loads((DATA_DIR / "sub_NAT100.json").read_text()))
der = {(r["iid"], r["t"]): r for r in read_shards(DATA_DIR / "derivations.jsonl")}
# latencies as in item7 §7c: the held-out-stage ledger (entries before item7 was generated, i.e. before the r1 GPU runs);
# judge = every non-derivation call (as item7), cert = the 1,099 certificate-construction calls of that stage
CUT = 1791129855.3
lat = {}
for l in open(DATA_DIR / "llm_ledger.jsonl", encoding="utf-8", errors="replace"):
    try:
        x = json.loads(l)
    except Exception:
        continue
    if x.get("model") == "ollama:qwen3.6:27b" and x.get("t", 0) <= CUT:
        tg = x.get("tag") or ""
        lat.setdefault("derive" if tg == "esm_derive" else "judge", []).append(x.get("lat", 0.0))
        if tg.startswith("cert"):
            lat.setdefault("cert", []).append(x.get("lat", 0.0))
mlat = {k: float(np.median(v)) for k, v in lat.items()}
KIND = {"CERT-ZS": "certzs", "CERT-v0": "certv0h"}


def arm(pol, sch, ids, path=None):
    if path is None:
        d = records(pol, sch, columns=["iid", "t", "eval_calls", "n_der", "eval_tok", "der_tok"])
    else:
        d = pd.read_parquet(path / f"{pol}__{sch}.parquet", columns=["iid", "t", "eval_calls", "n_der", "eval_tok", "der_tok"])
    d = d[d.iid.isin(ids)]
    g = d.groupby("iid")
    tok = (g.eval_tok.sum() + g.der_tok.sum()).astype(float)
    dr = d[d.n_der > 0]
    llm_d = dr.apply(lambda r: (der.get((r.iid, int(r.t))) or {}).get("n_llm", 0), axis=1) if len(dr) else pd.Series(dtype=float)
    calls = g.eval_calls.sum().astype(float).add(llm_d.groupby(dr.iid).sum() if len(dr) else 0, fill_value=0)
    mins = (g.eval_calls.sum().astype(float) * mlat["judge"]).add((llm_d.groupby(dr.iid).sum() * mlat["derive"]) if len(dr) else 0, fill_value=0) / 60
    f = pd.DataFrame({"tok": tok, "calls": calls, "mins": mins}).fillna(0.0)
    k = KIND.get(pol)
    f["c_tok"] = [CC.get(f"{i}|{k}", {}).get("tokens", 0) if k else 0 for i in f.index]
    f["c_calls"] = [CC.get(f"{i}|{k}", {}).get("calls", 0) if k else 0 for i in f.index]
    f["c_mins"] = f.c_calls * mlat["cert"] / 60
    return f


def rstat(num, den, ids):
    s = ratio_stats(num, den, [FX[i]["repo"] for i in ids])
    return s["est"], s["fact_ci"], s["clu_ci"]


L, OUT = ["# Round 2, point 4 — certificate construction in the cost accounting (generated by cost_construction.py)\n",
          f"Median 27B latencies from the ledger: judge {mlat['judge']:.1f} s, derivation turn {mlat['derive']:.1f} s, certificate construction "
          f"call {mlat['cert']:.1f} s (n = {len(lat['cert'])}). Steady state = maintenance only (judge + re-derivation + certificate re-execution); "
          "incl. construction = plus the one-time certificate construction at s0 (CERT-ZS: 1 extraction call; CERT-v0h: 1 proposal call + "
          "sufficiency-test calls). Ratios are pooled policy / ESM on the same facts; CIs: fact / repository-cluster bootstrap (B = 2000).\n"], {}
SETS = [("S160", "every", H150, None), ("S160", "every50", H150, None), ("NAT100", "every", NAT100, SIMR1)]
for name, sch, S, path in SETS:
    pols = ["ESM-norepair", "CERT-ZS", "CERT-v0"] + (["LLMDIFF", "REPLAY", "TTL100"] if sch == "every" else ["LLMDIFF", "REPLAY"])
    A = {p: arm(p, sch, S, path) for p in pols}
    L.append(f"\n## {name}, {sch}\n")
    L.append("| policy | facts | tokens/fact steady | constr. tokens/fact | tokens/fact incl. | LLM calls/fact steady | constr. calls/fact | calls incl. | est. min steady | est. min incl. | "
             "token ratio steady [fact CI] [repo CI] | token ratio incl. [fact CI] [repo CI] | call ratio steady | call ratio incl. [repo CI] | min ratio incl. |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for p in pols:
        f = A[p]; ids = sorted(f.index)
        e = A["ESM-norepair"].loc[ids]
        row = {"n": len(ids), "tok": f.tok.mean(), "c_tok": f.c_tok.mean(), "tok_incl": (f.tok + f.c_tok).mean(),
               "calls": f.calls.mean(), "c_calls": f.c_calls.mean(), "calls_incl": (f.calls + f.c_calls).mean(),
               "mins": f.mins.mean(), "mins_incl": (f.mins + f.c_mins).mean(),
               "esm_tok": e.tok.mean(), "esm_calls": e.calls.mean(), "esm_mins": e.mins.mean()}
        if p != "ESM-norepair":
            row["tr_ss"] = rstat(f.tok, e.tok, ids); row["tr_in"] = rstat(f.tok + f.c_tok, e.tok, ids)
            row["cr_ss"] = rstat(f.calls, e.calls, ids); row["cr_in"] = rstat(f.calls + f.c_calls, e.calls, ids)
            row["mr_in"] = rstat(f.mins + f.c_mins, e.mins, ids)
        OUT[f"{name}|{sch}|{p}"] = row
        fm = lambda r: f"{r[0]:.2f} [{r[1][0]:.2f}, {r[1][1]:.2f}] [{r[2][0]:.2f}, {r[2][1]:.2f}]"
        L.append(f"| {p} | {len(ids)} | {row['tok'] / 1e3:.1f}k | {row['c_tok'] / 1e3:.1f}k | {row['tok_incl'] / 1e3:.1f}k | {row['calls']:.1f} | {row['c_calls']:.2f} | "
                 f"{row['calls_incl']:.1f} | {row['mins']:.1f} | {row['mins_incl']:.1f} | "
                 + (f"{fm(row['tr_ss'])} | {fm(row['tr_in'])} | {row['cr_ss'][0]:.2f} | {row['cr_in'][0]:.2f} [{row['cr_in'][2][0]:.2f}, {row['cr_in'][2][1]:.2f}] | {row['mr_in'][0]:.2f} |"
                    if p != "ESM-norepair" else "– | – | – | – | – |")
                 + (f" (ESM on these {len(ids)} facts: {row['esm_tok'] / 1e3:.1f}k, {row['esm_calls']:.1f} calls, {row['esm_mins']:.1f} min)" if len(ids) != len(A['ESM-norepair']) else ""))
(OUTDIR / "cost_construction.md").write_text("\n".join(L), encoding="utf-8")
(OUTDIR / "cost_construction.json").write_text(json.dumps(OUT, indent=1, default=float), encoding="utf-8")
print("\n".join(L))
