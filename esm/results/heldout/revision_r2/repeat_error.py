"""Fig. 4d ("the agent repeats its error about 90 % of the time"): which derivations the
7,390 pairs of item6 section 6c come from, whether duplicates are counted, how concentrated they are, and the same
statistic on (i) consecutive derivations only and (ii) the main ESM run only.  Zero LLM, zero GPU.

Derivation store: esm_data_heldout/derivations.jsonl + shards = every 27B derivation of a kept held-out fact made by any
arm (s0 derivations, the main run, all S160 baselines / ablations / grids).  A derivation is cached per (fact, commit):
arms that re-derive the same fact at the same commit share ONE stored derivation (item6 also drops duplicate keys).
Item6 used the shards that existed when it ran (before the round-1 GPU runs); this script uses the same cut-off.
Output: repeat_error.md, repeat_error.json."""
import json, sys
from collections import Counter
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "revision_r1"))
from r1_common import *                    # noqa
OUTDIR = Path(__file__).resolve().parent
CUT = 1791129720.0          # item6.md generation time (2026-10-05 00:02); shards written later belong to the r1 runs

rows = []
for p in [DATA_DIR / "derivations.jsonl"] + sorted(DATA_DIR.glob("derivations.*.jsonl")):
    if p.stat().st_mtime > CUT:
        continue
    for l in p.read_text(encoding="utf-8", errors="replace").splitlines():
        try:
            r = json.loads(l)
        except Exception:
            continue
        if r["iid"] in FX:
            rows.append({"iid": r["iid"], "t": int(r["t"]), "c": bool(r["correct"]), "ans": str(r.get("answer"))})
raw = pd.DataFrame(rows)
der = raw.drop_duplicates(["iid", "t"]).sort_values(["iid", "t"]).reset_index(drop=True)
L, OUT = ["# Round 2, point 2 - the repeated-error statistic of Fig. 4d (generated by repeat_error.py)\n"], {}
L.append(f"Derivation records of kept held-out facts in the store at item6 time: {len(raw)}; unique (fact, commit): {len(der)} "
         f"({len(raw) - len(der)} duplicate keys dropped, as in item6); facts {der.iid.nunique()}; s0 derivations {int((der.t == 0).sum())}; "
         f"t > 0: {int((der.t > 0).sum())}.\n")

# which real (27B-agent) arms re-derived at each t>0 derivation (records.parquet rows with n_der > 0)
rec = pd.read_parquet(REC_PATH, columns=["policy", "schedule", "iid", "t", "n_der"])
rec = rec[(rec.n_der > 0) & rec.iid.isin(ALL) & ~rec.policy.str.contains("@oracle")]   # @oracle arms use the oracle, not the agent
arms = rec.assign(arm=rec.policy + "|" + rec.schedule).groupby(["iid", "t"]).arm.apply(lambda s: sorted(set(s))).to_dict()
der["arms"] = [arms.get((i, t), []) if t > 0 else ["s0"] for i, t in zip(der.iid, der.t)]
MAIN = f"{FROZEN}|every"
der["main"] = [(t == 0) or (MAIN in a) for t, a in zip(der.t, der.arms)]
der["n_arms"] = [len(a) for a in der.arms]
pos = der[der.t > 0]
L.append(f"t > 0 derivations: {len(pos)}; of them made (also) by the main run ({MAIN}, ALL): {int(pos.main.sum())}; "
         f"by no arm in records.parquet: {int((pos.n_arms == 0).sum())}; shared by >= 2 real arms: {int((pos.n_arms >= 2).sum())} "
         f"(stored and counted once). Facts with a t > 0 derivation: {pos.iid.nunique()} (S160: {pos[pos.iid.isin(H150)].iid.nunique()}); "
         f"share of t > 0 derivations on S160 facts: {100 * pos.iid.isin(H150).mean():.1f} %.\n")
armc = Counter(a for a_ in pos.arms for a in a_)
L.append("| arm (policy|schedule) | t > 0 derivations it triggered |\n|---|---|")
for a, n in armc.most_common(30):
    L.append(f"| {a} | {n} |")
OUT["store"] = {"raw": len(raw), "unique": len(der), "pos": len(pos), "main_pos": int(pos.main.sum()),
                "s160_share": float(pos.iid.isin(H150).mean()), "arms": dict(armc)}


def unchanged_strict(iid, a, b):
    v = truth(iid, a)
    return all(truth(iid, u) == v for u in range(a, b + 1))


def make_pairs(D, mode):
    """mode: 'all' (item6: every i<j, truth equal at the two commits), 'next' (consecutive derivations, truth equal at both),
    'next_strict' (consecutive, truth constant over the whole interval)."""
    P = []
    for iid, x in D.groupby("iid"):
        xs = x.sort_values("t").to_dict("records")
        for i in range(len(xs)):
            js = range(i + 1, len(xs)) if mode == "all" else range(i + 1, min(i + 2, len(xs)))
            for j in js:
                a, b = xs[i], xs[j]
                same = (truth(iid, a["t"]) == truth(iid, b["t"])) if mode != "next_strict" else unchanged_strict(iid, a["t"], b["t"])
                P.append({"iid": iid, "repo": FX[iid]["repo"], "prev": a["c"], "same": same, "next": b["c"],
                          "same_ans": a["ans"] == b["ans"], "t0": a["t"], "t1": b["t"]})
    return pd.DataFrame(P)


def summarise(P, label):
    W = P[(~P.prev) & P.same]
    R = P[P.prev & P.same]
    res = {"label": label, "pairs_wrong_unch": len(W), "p_right_after_wrong": float(W.next.mean()) if len(W) else float("nan"),
           "pairs_right_unch": len(R), "p_right_after_right": float(R.next.mean()) if len(R) else float("nan"),
           "facts": int(W.iid.nunique()), "repos": int(W.repo.nunique())}
    if len(W):
        g = W.groupby("iid").next.agg(["mean", "size"]).sort_values("size", ascending=False)
        res["fact_mean"] = float(g["mean"].mean())                                  # each fact weighted equally
        res["top1_share"] = float(g["size"].iloc[0] / len(W)); res["top1"] = g.index[0]
        res["top5_share"] = float(g["size"].iloc[:5].sum() / len(W))
        res["median_pairs_per_fact"] = float(g["size"].median())
        res["same_answer_share"] = float(W.same_ans.mean())
        rp = W.groupby("repo").next.agg(["mean", "size"])
        res["per_repo"] = {r: (float(m), int(n)) for r, (m, n) in rp.iterrows()}
        res["jinja_share"] = float((W.repo == "jinja").mean())
        nj = W[W.repo != "jinja"]
        res["without_jinja"] = (float(nj.next.mean()) if len(nj) else float("nan"), int(len(nj)))
        reps = sorted(rp.index)
        num = np.array([W[W.repo == r].next.sum() for r in reps], float)
        den = rp.loc[reps, "size"].to_numpy(float)
        rng = np.random.default_rng(7)
        dr = rng.integers(0, len(reps), size=(B, len(reps)))
        cnt = np.stack([(dr == j).sum(1) for j in range(len(reps))], 1)
        res["repo_ci"] = np.percentile((cnt @ num) / np.maximum(cnt @ den, 1), [2.5, 97.5]).tolist()
        fm = g["mean"].to_numpy()
        res["fact_mean_ci"] = np.percentile(fm[rng.integers(0, len(fm), size=(B, len(fm)))].mean(1), [2.5, 97.5]).tolist()
    return res


def fmt(r):
    if not r["pairs_wrong_unch"]:
        return f"| {r['label']} | 0 | - | - | - | - | - | - | - | {r['pairs_right_unch']} | {100 * r['p_right_after_right']:.1f} |"
    return (f"| {r['label']} | {r['pairs_wrong_unch']} | {r['facts']} / {r['repos']} | **{100 * r['p_right_after_wrong']:.1f}** "
            f"[{100 * r['repo_ci'][0]:.1f}, {100 * r['repo_ci'][1]:.1f}] | {100 * r['fact_mean']:.1f} [{100 * r['fact_mean_ci'][0]:.1f}, {100 * r['fact_mean_ci'][1]:.1f}] "
            f"| {100 * r['top1_share']:.0f} % ({r['top1']}) / {100 * r['top5_share']:.0f} % | {100 * r['jinja_share']:.0f} % | "
            f"{100 * r['without_jinja'][0]:.1f} (n = {r['without_jinja'][1]}) | {100 * r['same_answer_share']:.0f} % | {r['pairs_right_unch']} | {100 * r['p_right_after_right']:.1f} |")


RUNS = [("A", "item6 / Fig. 4d as published: every later derivation of the fact (all pairs i < j), pooled unique store", der, "all"),
        ("B", "pooled unique store, next derivation only, truth equal at both commits", der, "next"),
        ("C", "pooled unique store, next derivation only, truth constant in between", der, "next_strict"),
        ("D", "main run only (s0 + ESM re-derivations, ALL), next derivation, truth equal at both", der[der.main], "next"),
        ("E", "main run only, next derivation, truth constant in between", der[der.main], "next_strict"),
        ("F", "pooled store, S160 facts only, next derivation, truth constant", der[der.iid.isin(H150)], "next_strict"),
        ("G", "pooled store, facts outside S160, next derivation, truth constant", der[~der.iid.isin(H150)], "next_strict")]
L.append("\n## Pairs (previous derivation wrong, truth unchanged -> is the next one right?)\n")
L.append("| definition | pairs | facts / repos | P(right) % [repo-cluster CI] | fact-weighted mean % [fact CI] | top-1 fact / top-5 share of pairs | jinja share | without jinja % | identical answer string | pairs prev right, truth unch. | P(right after right) % |")
L.append("|---|---|---|---|---|---|---|---|---|---|---|")
for key, lab, D, mode in RUNS:
    r = summarise(make_pairs(D, mode), f"{key}. {lab}")
    OUT[key] = r
    L.append(fmt(r))
for key in ("C", "E"):
    r = OUT[key]
    if r["pairs_wrong_unch"]:
        L.append(f"\nPer-repository detail of {key}:\n")
        L.append("| repo | P(right) % | pairs |\n|---|---|---|")
        for rp, (m, n) in sorted(r["per_repo"].items(), key=lambda kv: -kv[1][1]):
            L.append(f"| {rp} | {100 * m:.1f} | {n} |")
(OUTDIR / "repeat_error.md").write_text("\n".join(L), encoding="utf-8")
(OUTDIR / "repeat_error.json").write_text(json.dumps(OUT, indent=1, default=lambda o: o.item() if hasattr(o, "item") else str(o)), encoding="utf-8")
print("\n".join(L))
