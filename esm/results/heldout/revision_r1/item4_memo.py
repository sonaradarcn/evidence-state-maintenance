"""State-memoisation ablation from the recorded runs.
In simulate_esm (esm/maintain.py) a memo hit happens only for a (anchor, evidence state) pair already judged still_valid
(or unsure with unsure=fresh); the record of a memo hit carries `nomemo_calls` / `nomemo_tok` = the calls / tokens of the
judgement that would be repeated.  The judge prompt is a function of (anchor evidence, current outputs) only, and the
outputs are what the state hashes, and every judge call is at T = 0 through the LLM cache, so without memoisation the
same prompt would be re-issued and return the same verdict: served answers, re-derivations and accuracy are IDENTICAL,
and only the judge cost changes.  The no-memo cost is therefore exact under that determinism assumption (it is not a
run).
Output: item4.md, item4.json, fig_item4_memo.png."""
import json
from r1_common import *
from r1_common import _w_fact, _w_repo
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

L, OUT = ["# Item 4 — memoisation ablation (generated by item4_memo.py)\n"], {}


def per_fact_memo(policy, schedule):
    d = records(policy, schedule, columns=["iid", "t", "action", "eval_tok", "eval_calls", "der_tok", "n_der", "nomemo_tok",
                                           "nomemo_calls", "served_valid"])
    d["chg"] = d.action != "same"
    d["fresh_eval"] = d.eval_calls > 0
    d["memo"] = d.action == "memo"
    g = d.groupby("iid")
    f = pd.DataFrame({"reads": g.size(), "chg_reads": g.chg.sum(), "evals": g.fresh_eval.sum(), "memo_hits": g.memo.sum(),
                      "eval_tok": g.eval_tok.sum(), "eval_calls": g.eval_calls.sum(), "der_tok": g.der_tok.sum(),
                      "n_der": g.n_der.sum(), "nomemo_tok": g.nomemo_tok.sum(), "nomemo_calls": g.nomemo_calls.sum(),
                      "sw": g.served_valid.apply(lambda x: int((~x).sum()))})
    f["tok"] = f.eval_tok + f.der_tok
    f["tok_nm"] = f.nomemo_tok + f.der_tok
    f["repo"] = [FX[i]["repo"] for i in f.index]
    return f


SETS = {"ALL": ALL, "natural": NAT, "enriched": ENR, "static": STA, "behaviour": BEH, "without jinja": NOJ, "H150": H150}
L.append("## 4a. ESM (frozen) at every commit: with vs without per-state memoisation\n")
L.append("changed-state reads = reads whose evidence state differs from the current anchor's (action ≠ same); fresh judgements = "
         "distinct (anchor, state) pairs actually judged; memo hits = changed-state reads served from the memo. "
         "Tokens = judge + re-derivation tokens per fact. Without memo, every changed-state read is judged again.\n")
L.append("| set | facts | changed-state reads/fact | fresh judgements/fact | memo hits/fact | judge calls/fact (memo → none) | tokens/fact with memo | tokens/fact without memo [cluster CI of Δ] | × | served-wrong % (both) |\n|---|---|---|---|---|---|---|---|---|---|")
f = per_fact_memo(FROZEN, "every")
rng = np.random.default_rng(0)
for nm, ids in SETS.items():
    x = f.loc[sorted(ids & set(f.index))]
    diff = (x.tok_nm - x.tok).to_numpy(float)
    reps = sorted(set(x.repo)); ridx = np.array([reps.index(r) for r in x.repo])
    Wc = _w_repo(ridx, len(reps), rng)
    Wf = _w_fact(len(x), rng)
    cl = np.percentile((Wc @ diff) / Wc.sum(1), [2.5, 97.5]); fl = np.percentile((Wf @ diff) / Wf.sum(1), [2.5, 97.5])
    o = {k: float(x[k].mean()) for k in ("chg_reads", "evals", "memo_hits", "eval_calls", "nomemo_calls", "tok", "tok_nm", "n_der")}
    o.update(n=len(x), sw=float(x.sw.sum() / x.reads.sum()), dtok_fact_ci=fl.tolist(), dtok_clu_ci=cl.tolist())
    OUT[f"every|{nm}"] = o
    L.append(f"| {nm} | {len(x)} | {o['chg_reads']:.1f} | {o['evals']:.2f} | {o['memo_hits']:.1f} | {o['eval_calls']:.1f} → {o['nomemo_calls']:.1f} "
             f"| {o['tok'] / 1000:.1f}k | {o['tok_nm'] / 1000:.1f}k [+{cl[0] / 1000:.0f}k, +{cl[1] / 1000:.0f}k] | {o['tok_nm'] / o['tok']:.1f} | {p1(o['sw'])} |")

L.append("\n## 4b. Read schedules on H150 (memo saves less when reads are sparse)\n")
L.append("| schedule | reads/fact | changed-state reads/fact | fresh judgements/fact | tokens/fact with memo | without memo | × |\n|---|---|---|---|---|---|---|")
for sch in ("every", "every5", "bursty", "every20", "every50"):
    x = per_fact_memo(FROZEN, sch).loc[sorted(H150)]
    OUT[f"sched|{sch}|H150"] = {"reads": float(x.reads.mean()), "tok": float(x.tok.mean()), "tok_nm": float(x.tok_nm.mean())}
    L.append(f"| {sch} | {x.reads.mean():.0f} | {x.chg_reads.mean():.1f} | {x.evals.mean():.2f} | {x.tok.mean() / 1000:.1f}k | {x.tok_nm.mean() / 1000:.1f}k | {x.tok_nm.mean() / x.tok.mean():.1f} |")

L.append("\n## 4c. Same comparison for the other ESM arms on H150 (every commit)\n")
L.append("| arm | tokens/fact with memo | without memo | × |\n|---|---|---|---|")
for arm in ("ESM-norepair", "ESM-verify", "ESM", "ESM-norepair-noanchor", "ESM-norepair-trunc", "ESM-norepair-unsurefresh", "ESM-norepair-n2",
            "ESM-norepair-9B", "ESM-norepair-9Bderiver"):
    x = per_fact_memo(arm, "every").loc[sorted(H150)]
    OUT[f"arm|{arm}"] = {"tok": float(x.tok.mean()), "tok_nm": float(x.tok_nm.mean())}
    L.append(f"| {arm} | {x.tok.mean() / 1000:.1f}k | {x.tok_nm.mean() / 1000:.1f}k | {x.tok_nm.mean() / x.tok.mean():.1f} |")

h = OUT["every|H150"]
L.append("\n## 4d. Row for Table 5 (H150, every commit; Δ = frozen ESM − variant)\n")
L.append("| Variant | Wrong % | Δ wrong [CI] | Tok./fact | Re-der. |\n|---|---|---|---|---|")
L.append(f"| no memoisation (counterfactual; identical verdicts under the deterministic cached judge) | {p1(h['sw'])} | +0.0 (identical by construction) "
         f"| {h['tok_nm'] / 1000:.1f}k (Δ tokens −{(h['tok_nm'] - h['tok']) / 1000:.0f}k [−{h['dtok_clu_ci'][1] / 1000:.0f}k, −{h['dtok_clu_ci'][0] / 1000:.0f}k] cluster CI) | {h['n_der']:.2f} |")

# figure: per-fact changed-state reads vs fresh judgements
x = f.loc[sorted(ALL)]
fig, ax = plt.subplots(figsize=(6, 4.6))
ax.scatter(x.evals + 0.5, x.chg_reads + 0.5, s=6, alpha=0.4, color="#3b6fb6")
lim = [0.4, 500]
ax.plot(lim, lim, color="grey", lw=0.8, ls="--")
ax.set_xscale("log"); ax.set_yscale("log"); ax.set_xlim(lim); ax.set_ylim(lim)
ax.set_xlabel("distinct (anchor, state) judgements per fact (+0.5)"); ax.set_ylabel("changed-state reads per fact (+0.5)")
ax.set_title(f"ESM on ALL, every commit: memo turns {OUT['every|ALL']['chg_reads']:.0f} changed-state reads\ninto {OUT['every|ALL']['evals']:.1f} judgements per fact (means)", fontsize=9)
fig.tight_layout(); fig.savefig(HERE / "fig_item4_memo.png", dpi=140); plt.close(fig)

(HERE / "item4.md").write_text("\n".join(L), encoding="utf-8")
(HERE / "item4.json").write_text(json.dumps(OUT, indent=1, default=float), encoding="utf-8")
print("\n".join(L))
