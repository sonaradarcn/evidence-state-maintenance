"""Cost and accuracy of the real-cost baselines re-weighted to the natural distribution.
H150 (160 facts) over-samples changing facts.  Each H150 fact gets a post-stratification weight
    w_i = P_natural(stratum) / P_H150(stratum),  stratum = (fact type, changes in FUTURE yes/no)
where P_natural is the distribution over the 715 kept natural-subset facts.  Strata of the natural subset with no H150
fact cannot be represented; their natural mass is reported and the remaining weights are renormalised.
Weighted served-wrong = Σ w sw / Σ w reads; weighted tokens/fact = Σ w tok / Σ w.
CIs: (i) stratified fact bootstrap (facts resampled within strata), (ii) repo-cluster bootstrap; B = 2000.
Validation: policies that were run on ALL facts (ESM, NEVER, @oracle baselines) — their re-weighted H150 value is compared
with their actual value on the natural subset.
Also: the 71 natural H150 facts alone (no weighting), and a coarser stratification (slice x changing).
Output: item3.md, item3.json, fig_item3_cost.png."""
