def stratum(i, scheme):
    f = FX[i]
    if scheme == "type x changing":
        return (f["type"], changing(i))
    return (f["slice"], changing(i))


def weights(ids, scheme, target=NAT):
    ids = sorted(ids)
    sh = pd.Series([stratum(i, scheme) for i in ids], index=ids)
    sn = pd.Series([stratum(i, scheme) for i in target])
    pn = sn.value_counts(normalize=True)
    ph = sh.value_counts(normalize=True)
    covered = [s for s in pn.index if s in ph.index]
    unc = float(pn.drop(covered).sum())
    w = sh.map(lambda s: pn.get(s, 0.0) / ph[s])
    return w, unc, pn, ph


