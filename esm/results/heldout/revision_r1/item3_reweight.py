def wstats(p, ids, wser, seed=0):
    ids = sorted(set(ids) & set(p.index))
    x = p.loc[ids]
    ww = wser.loc[ids].to_numpy(float)
    sw, rd, tok = x.sw.to_numpy(float), x.reads.to_numpy(float), x.tok.to_numpy(float)
    est_sw = (ww * sw).sum() / (ww * rd).sum()
    est_tok = (ww * tok).sum() / ww.sum()
    return est_sw, est_tok, ids


def boot_weighted(pa, pb, ids, wser, scheme, seed=0):
    """paired weighted Δ served-wrong, weighted tokens of A and B and their ratio, with stratified-fact and repo-cluster CIs."""
    ids = sorted(set(ids) & set(pa.index) & (set(pb.index) if pb is not None else set(pa.index)))
    ww = wser.loc[ids].to_numpy(float)
    A = pa.loc[ids]
    arrs = [A.sw.to_numpy(float), A.reads.to_numpy(float), A.tok.to_numpy(float)]
    if pb is not None:
        Bb = pb.loc[ids]
        arrs += [Bb.sw.to_numpy(float), Bb.reads.to_numpy(float), Bb.tok.to_numpy(float)]
    strata = np.array([str(stratum(i, scheme)) for i in ids])
    repo = np.array([FX[i]["repo"] for i in ids]); reps = sorted(set(repo)); ridx = np.array([reps.index(r) for r in repo])
    rng = np.random.default_rng(seed)

    def stat(W):            # W: (nb, n) resampling multiplicities
        WW = W * ww
        swa = (WW @ arrs[0]) / (WW @ arrs[1]); toka = (WW @ arrs[2]) / WW.sum(1)
        if pb is None:
            return swa, toka, None, None
        swb = (WW @ arrs[3]) / (WW @ arrs[4]); tokb = (WW @ arrs[5]) / WW.sum(1)
        return swa, toka, swb, tokb

    n = len(ids)
    est = stat(np.ones((1, n)))
    # stratified fact bootstrap
    Wf = np.zeros((B, n))
    for s in set(strata):
        m = np.where(strata == s)[0]
        dr = rng.integers(0, len(m), size=(B, len(m)))
        for k in range(len(m)):
            Wf[:, m] += (dr[:, [k]] == np.arange(len(m))[None, :])
    Wc = _w_repo(ridx, len(reps), rng)
    out = {"n": n, "sw_a": est[0][0], "tok_a": est[1][0]}
    for lab, W in (("fact", Wf), ("clu", Wc)):
        s = stat(W)
        out[f"sw_a_{lab}"] = np.percentile(s[0], [2.5, 97.5]).tolist()
        out[f"tok_a_{lab}"] = np.percentile(s[1], [2.5, 97.5]).tolist()
        if pb is not None:
            out[f"d_{lab}"] = np.percentile(s[0] - s[2], [2.5, 97.5, 5, 95]).tolist()
            out[f"ratio_{lab}"] = np.percentile(s[3] / s[1], [2.5, 97.5]).tolist()
            out[f"sw_b_{lab}"] = np.percentile(s[2], [2.5, 97.5]).tolist()
    if pb is not None:
        out.update(sw_b=est[2][0], tok_b=est[3][0], d=est[0][0] - est[2][0], ratio=est[3][0] / est[1][0])
    return out


