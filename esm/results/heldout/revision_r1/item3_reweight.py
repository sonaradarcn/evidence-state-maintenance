# finer churn bins: number of FUTURE commits at which the stored answer is invalid
def ninv(i):
    return sum(not v for v in FX[i]["valid"])


def fbin(i):
    n = ninv(i)
    return "0" if n == 0 else ("1-100" if n <= 100 else ("101-200" if n <= 200 else "201-400"))


