"""Small factual checks for the paper.
(a) every place in the paper sources where 'H150' / '150 facts' / 'H80R' and the review's flagged wordings occur;
(b) re-check of Table 4 / Table 5 numbers against the records;
(c) non-token cost counts per policy (tool executions, LLM calls) for the 'LLM-token cost' minor issue;
(d) small factual checks quoted in the review.
Output: item7.md, item7.json."""
import json, re
from r1_common import *
from esm.maintain import read_shards

L, OUT = ["# Item 7 — minor factual issues (generated by item7_minor.py)\n"], {}
PAPER = ROOT / "paper"
files = sorted((PAPER / "sections").glob("*.tex")) + [PAPER / "main.tex"] + sorted((PAPER / "figs").glob("*.py"))
PATS = [("H150 name", r"H150|H\\,?150|150 facts|150-fact|H80R"),
        ("'tie' wording", r"statistically tied|\btie[sd]?\b|\bmatch(es|ed)?\b accuracy|same accuracy"),
        ("'measured rather than assumed'", r"measured rather"),
        ("cost ratio headline", r"times lower cost|times cheaper|lower token cost|2\.0--2\.7|2--3"),
        ("Section 4 title", r"section\{Why cheap")]
L.append("## 7a. Occurrences in paper sources (file:line, excerpt)\n")
OUT["grep"] = {}
for name, pat in PATS:
    L.append(f"\n### {name} — pattern `{pat}`\n")
    L.append("| file:line | excerpt |\n|---|---|")
    hits = []
    for f in files:
        for n, line in enumerate(f.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for m in re.finditer(pat, line):
                a, b = max(0, m.start() - 70), min(len(line), m.end() + 70)
                ex = line[a:b].replace("|", "\\|")
                hits.append(f"{f.relative_to(PAPER).as_posix()}:{n}")
                L.append(f"| {f.relative_to(PAPER).as_posix()}:{n} | …{ex}… |")
    OUT["grep"][name] = hits
    L.append(f"\n{len(hits)} occurrence(s).")

# ---------------------------------------------------------------- (b) Table 4 / Table 5 re-check
paper_t4 = {"ESM-norepair": (6.9, 26.5, None), "REPLAY": (8.5, 162.4, None), "CERT-ZS": (7.1, 53.1, None), "CERT-v0": (6.4, 26.6, None),
            "LLMDIFF": (8.1, 72.3, None), "TTL50": (12.0, 86.3, None), "TTL100": (14.6, 44.0, None), "TTL200": (20.9, 22.5, None),
            "NEVER": (28.8, 0.0, None)}
paper_t5 = {"ESM-norepair": (6.9, 26.5, 1.31), "ESM-verify": (6.8, 20.9, 0.73), "ESM": (11.0, 16.2, 0.53), "ESM-norepair-noanchor": (6.7, 40.5, 2.51),
            "ESM-norepair-trunc": (6.9, 25.4, 1.31), "ESM-norepair-unsurefresh": (6.6, 22.6, 1.05), "ESM-norepair-n2": (6.7, 42.8, 1.74),
            "ESM-norepair-9B": (8.4, 57.6, 2.66), "ESM-norepair-9Bderiver": (11.1, 41.1, 1.35)}
L.append("\n## 7b. Table 4 / Table 5 values in the paper vs recomputed from records.parquet (H150, every commit)\n")
L.append("| table | policy | paper wrong % | recomputed | paper tok/fact | recomputed | paper re-der./fact | recomputed | match |\n|---|---|---|---|---|---|---|---|---|")
OUT["recheck"] = {}
for tab, dd in (("Table 4", paper_t4), ("Table 5", paper_t5)):
    for pol, (pw, pt, pr) in dd.items():
        p = pf(pol).loc[sorted(H150 & set(pf(pol).index))]
        w, t, r = 100 * p.sw.sum() / p.reads.sum(), p.tok.mean() / 1000, p.n_der.mean()
        ok = abs(w - pw) < 0.0501 and abs(t - pt) < 0.0501 and (pr is None or abs(r - pr) < 0.00501)
        OUT["recheck"][f"{tab}|{pol}"] = (w, t, r, ok)
        L.append(f"| {tab} | {pol} | {pw} | {w:.1f} | {pt}k | {t:.1f}k | {pr if pr is not None else '–'} | {r:.2f} | {'yes' if ok else '**NO**'} |")

# ---------------------------------------------------------------- (c) non-token cost counts
der = {(r["iid"], r["t"]): r for r in read_shards(DATA_DIR / "derivations.jsonl")}
lat = {}
for l in open(DATA_DIR / "llm_ledger.jsonl", encoding="utf-8", errors="replace"):
    try:
        x = json.loads(l)
    except Exception:
        continue
    if x.get("model") == "ollama:qwen3.6:27b":
        lat.setdefault("derive" if x.get("tag") == "esm_derive" else "judge", []).append(x.get("lat", 0.0))
mlat = {k: float(np.median(v)) for k, v in lat.items()}
L.append("\n## 7c. Non-token cost per fact (H150, 160 facts): tool executions and LLM calls\n")
L.append(f"Guard tool executions = observations the policy's check replays or hashes per read, summed over reads (`guard_io`: evidence queries "
         f"for ESM / REPLAY, read-set files for FILEHASH / ASTHASH / LLMDIFF, citations for CITE, certificate calls for CERT-*). Re-derivation "
         f"tool calls / LLM calls = the recorded agent traces of the re-derivations the policy triggered. Serial LLM time = calls × median "
         f"per-call latency in the ledger (27B, measured with 2–4 requests in flight per GPU: judge {mlat.get('judge', float('nan')):.1f} s, "
         f"derivation turn {mlat.get('derive', float('nan')):.1f} s) — an indicative estimate, not a wall-clock measurement. Certificate "
         f"construction calls are not included.\n")
L.append("| policy (schedule) | guard tool executions/fact | re-derivations/fact | re-derivation tool calls/fact | re-derivation LLM calls/fact | judge LLM calls/fact | total LLM calls/fact | est. serial LLM minutes/fact | tokens/fact |\n|---|---|---|---|---|---|---|---|---|")
OUT["io"] = {}
for pol, sch in [(x, "every") for x in (FROZEN, "REPLAY", "CERT-ZS", "CERT-v0", "LLMDIFF", "TTL50", "TTL100", "TTL200")] + \
                [(x, "every50") for x in (FROZEN, "ALWAYS", "REPLAY", "FILEHASH", "ASTHASH", "CITE", "CERT-ZS", "LLMDIFF")]:
    r = records(pol, sch, columns=["iid", "t", "action", "guard_io", "eval_calls", "n_der"])
    r = r[r.iid.isin(H150)]
    nf = r.iid.nunique()
    dr = r[r.n_der > 0]
    tools = sum(len((der.get((i, int(t))) or {}).get("trace") or []) for i, t in zip(dr.iid, dr.t))
    llmc = sum((der.get((i, int(t))) or {}).get("n_llm", 0) for i, t in zip(dr.iid, dr.t))
    miss = sum(1 for i, t in zip(dr.iid, dr.t) if (i, int(t)) not in der)
    g, jc = r.guard_io.sum() / nf, r.eval_calls.sum() / nf
    mins = (llmc / nf * mlat.get("derive", 0) + jc * mlat.get("judge", 0)) / 60
    tok = pf(pol, sch).loc[sorted(H150 & set(pf(pol, sch).index))].tok.mean()
    OUT["io"][f"{pol}|{sch}"] = {"guard_io": g, "n_der": len(dr) / nf, "der_tools": tools / nf, "der_llm": llmc / nf, "judge": jc, "mins": mins, "missing": miss}
    L.append(f"| {pol} ({sch}) | {g:.0f} | {len(dr) / nf:.2f} | {tools / nf:.1f} | {llmc / nf:.1f} | {jc:.1f} | {llmc / nf + jc:.1f} | {mins:.1f} | {tok / 1000:.1f}k |"
             + (f" ({miss} derivations missing from store)" if miss else ""))

# ---------------------------------------------------------------- (d) small factual checks
L.append("\n## 7d. Small factual checks of statements quoted in the review\n")
jin = [i for i in ALL if FX[i]["repo"] == "jinja"]
chk = [("jinja kept facts / changing", f"{len(jin)} / {sum(changing(i) for i in jin)}", "paper: 93 / 90"),
       ("H150 size / changing / enriched / natural", f"{len(H150)} / {sum(changing(i) for i in H150)} / {sum(FX[i]['subset'] == 'enriched' for i in H150)} / "
        f"{sum(FX[i]['subset'] == 'natural' for i in H150)}", "paper: 160 / 94 / 89 / 71"),
       ("H150 facts per repo", ", ".join(sorted({str(sum(FX[i]['repo'] == r for i in H150)) for r in REPOS})), "paper: ten per repository"),
       ("H150 behaviour facts", str(sum(FX[i]['slice'] == 'behav' for i in H150)), "CERT-v0h covers the other 133"),
       ("ALL kept / changing", f"{len(ALL)} / {sum(changing(i) for i in ALL)}", "paper: 1,419 / 555")]
L.append("| check | recomputed | paper / note |\n|---|---|---|")
for a, b, c in chk:
    L.append(f"| {a} | {b} | {c} |")
OUT["checks"] = chk

(HERE / "item7.md").write_text("\n".join(L), encoding="utf-8")
(HERE / "item7.json").write_text(json.dumps(OUT, indent=1, default=lambda o: o.item() if hasattr(o, "item") else str(o)), encoding="utf-8")
print("\n".join(L))
