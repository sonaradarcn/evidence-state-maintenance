"""Repo-clustered statistics for the headline held-out numbers.
For each number: point estimate, fact-level bootstrap CI (the paper's method), repo-cluster bootstrap CI (repos resampled
with replacement, B = 2000), repo-level equal-weight mean with a CI over repos, leave-one-repo-out (LORO) min / max, and the
without-jinja variant.  Output: item1.md, item1.json, fig_item1_paired.png, fig_item1_perrepo.png."""
import json
from r1_common import *
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

L, OUT = [], {}
L.append("# Item 1 — clustered statistics (generated by item1_clustered.py)\n")
L.append("Fact CI = bootstrap over facts (paper's method; recomputed here with B = 2000, so it can differ from the paper's "
         "B = 1000 interval by ±0.1 pp of Monte-Carlo noise). Cluster CI = repositories resampled with replacement (B = 2000), "
         "all facts of a drawn repo kept, pooled ratio-of-sums. Repo mean = each repository's own pooled rate, averaged with equal "
         "weight (CI: bootstrap over repositories). LORO = min / max of the pooled estimate when one repository is dropped "
         "(the repo giving the extreme in parentheses).\n")

SETS = {"ALL": ALL, "natural": NAT, "enriched": ENR, "static": STA, "behaviour": BEH, "without jinja": NOJ}

# ---------------------------------------------------------------- Table 3 rates
L.append("\n## 1a. Table 3 served-wrong rates (ALL facts, every commit)\n")
L.append("| set | policy | facts | repos | estimate % | fact CI | cluster CI | repo mean % [CI over repos] | LORO min–max |\n|---|---|---|---|---|---|---|---|---|")
OUT["T3"] = {}
for sname, ids in SETS.items():
    for pol in (FROZEN, "NEVER", "TTL100@oracle", "TTL50@oracle", "REPLAY@oracle"):
        p = pf(pol)
        x = p.loc[sorted(ids & set(p.index))]
        r = ratio_stats(x.sw, x.reads, x.repo)
        OUT["T3"][f"{sname}|{pol}"] = r
        L.append(f"| {sname} | {pol} | {len(x)} | {r['n_repos']} | {p1(r['est'])} | {ci1(r['fact_ci'])} | {ci1(r['clu_ci'])} "
                 f"| {p1(r['repo_mean'])} {ci1(r['repo_mean_ci'])} | {p1(r['loro'][0])} ({r['loro_arg'][0]}) – {p1(r['loro'][1])} ({r['loro_arg'][1]}) |")

# ---------------------------------------------------------------- paired vs NEVER / @oracle on ALL
def paired_line(lbl, r, setname):
    sigf = "yes" if (r["fact"][0] > 0 or r["fact"][1] < 0) else "no"
    sigc = "yes" if (r["clu"][0] > 0 or r["clu"][1] < 0) else "no"
    return (f"| {lbl} | {setname} | {r['n']} / {r['n_repos']} | {100 * r['d']:+.1f} | {sci1(r['fact'][:2])} | {sci1(r['clu'][:2])} "
            f"| {100 * r['repo_mean']:+.1f} {sci1(r['repo_mean_ci'][:2])} | {r['repo_neg']} / {r['repo_zero']} / {r['repo_pos']} "
            f"| {r['sign_p']:.3g} | {100 * r['loro'][0]:+.1f} – {100 * r['loro'][1]:+.1f} | {sigf} / {sigc} "
            f"| {r['dt'] / 1000:+.1f}k [{r['fact_tok'][0] / 1000:+.1f}, {r['fact_tok'][1] / 1000:+.1f}] / [{r['clu_tok'][0] / 1000:+.1f}, {r['clu_tok'][1] / 1000:+.1f}] |")


PH = ("| ESM − B | set | facts / repos | Δ pp | fact CI | cluster CI | repo-mean Δ [CI over repos] | repos ESM better / tie / worse "
      "| sign-test p | LORO min–max | significant? fact / cluster | Δ tokens/fact, fact CI / cluster CI |\n|---|---|---|---|---|---|---|---|---|---|---|---|")
L.append("\n## 1b. Paired differences on ALL (Table 3 text)\n")
L.append(PH)
OUT["paired_ALL"] = {}
for b, sname in (("NEVER", "ALL"), ("NEVER", "natural"), ("NEVER", "behaviour"), ("NEVER", "without jinja"),
                 ("TTL100@oracle", "ALL"), ("TTL50@oracle", "ALL"), ("REPLAY@oracle", "ALL")):
    r = paired_stats(pf(FROZEN), pf(b), SETS[sname])
    OUT["paired_ALL"][f"{b}|{sname}"] = r
    L.append(paired_line(b, r, sname))

# ---------------------------------------------------------------- detection FF / FS
L.append("\n## 1c. Detection only (DETECT-anchor-hier = the ESM detector, ALL, every commit): FF and FS\n")
L.append("| set | metric | estimate % | fact CI | cluster CI | repo mean % [CI] | LORO min–max |\n|---|---|---|---|---|---|---|")
OUT["detect"] = {}
d = pf("DETECT-anchor-hier")
for sname in ("ALL", "static", "behaviour", "natural", "without jinja"):
    x = d.loc[sorted(SETS[sname] & set(d.index))]
    for m, num, den in (("FF", "ff", "ninv"), ("FS", "fs", "nval")):
        keep = x[den] > 0 if m == "FF" else x[den] >= 0
        y = x[keep]
        r = ratio_stats(y[num], y[den], y.repo)
        OUT["detect"][f"{sname}|{m}"] = r
        L.append(f"| {sname} | {m} | {p1(r['est'])} | {ci1(r['fact_ci'])} | {ci1(r['clu_ci'])} | {p1(r['repo_mean'])} {ci1(r['repo_mean_ci'])} "
                 f"| {p1(r['loro'][0])} ({r['loro_arg'][0]}) – {p1(r['loro'][1])} ({r['loro_arg'][1]}) |")

# ---------------------------------------------------------------- Table 4 (H150)
T4 = ["REPLAY", "CERT-ZS", "CERT-v0", "LLMDIFF", "TTL50", "TTL100", "TTL200", "NEVER"]
L.append("\n## 1d. Table 4 (H150, 160 facts, every commit): per-policy served-wrong\n")
L.append("| policy | facts | estimate % | fact CI | cluster CI | repo mean % [CI] | LORO min–max |\n|---|---|---|---|---|---|---|")
OUT["T4"] = {}
for pol in [FROZEN] + T4:
    p = pf(pol)
    x = p.loc[sorted(H150 & set(p.index))]
    r = ratio_stats(x.sw, x.reads, x.repo)
    OUT["T4"][pol] = r
    L.append(f"| {pol} | {len(x)} | {p1(r['est'])} | {ci1(r['fact_ci'])} | {ci1(r['clu_ci'])} | {p1(r['repo_mean'])} {ci1(r['repo_mean_ci'])} "
             f"| {p1(r['loro'][0])} ({r['loro_arg'][0]}) – {p1(r['loro'][1])} ({r['loro_arg'][1]}) |")

H150NJ = {i for i in H150 if FX[i]["repo"] != "jinja"}
L.append("\n## 1e. Table 4 paired differences ESM − B (H150, every commit), and the H150-without-jinja variant\n")
L.append(PH)
OUT["T4_paired"] = {}
for sname, ids in (("H150", H150), ("H150 w/o jinja", H150NJ)):
    for b in T4:
        r = paired_stats(pf(FROZEN), pf(b), ids)
        OUT["T4_paired"][f"{b}|{sname}"] = r
        L.append(paired_line(b, r, sname))

# ---------------------------------------------------------------- Table 5 ablations and the every50 grid
L.append("\n## 1f. Table 5 ablations (ESM − variant, H150, every commit) and the shared every50 grid (ESM − B)\n")
L.append(PH)
OUT["T5_paired"] = {}
for b in ("ESM-verify", "ESM", "ESM-norepair-noanchor", "ESM-norepair-trunc", "ESM-norepair-unsurefresh", "ESM-norepair-n2",
          "ESM-norepair-9B", "ESM-norepair-9Bderiver"):
    r = paired_stats(pf(FROZEN), pf(b), H150)
    OUT["T5_paired"][b] = r
    L.append(paired_line(b, r, "H150"))
for b in ("ALWAYS", "REPLAY", "FILEHASH", "ASTHASH", "CERT-ZS", "CERT-v0", "LLMDIFF", "CITE", "TTL100", "TTL200"):
    r = paired_stats(pf(FROZEN, "every50"), pf(b, "every50"), H150)
    OUT["T5_paired"][f"{b}|every50"] = r
    L.append(paired_line(b + " (every50)", r, "H150"))

# ---------------------------------------------------------------- per-repo table (minor issue: per-repo results)
L.append("\n## 1g. Per-repository served-wrong % (H150, every commit, 10 facts per repo; ALL-facts ESM and NEVER for reference)\n")
cols = [FROZEN, "NEVER", "CERT-ZS", "CERT-v0", "LLMDIFF", "REPLAY", "TTL50", "TTL100"]
L.append("| repo | ESM (ALL) | NEVER (ALL) | facts ALL | " + " | ".join(f"{c} (H150)" for c in cols) + " |\n|" + "---|" * (4 + len(cols)))
perrepo = {}
for rp in REPOS:
    row = [p1(OUT["T3"][f"ALL|{FROZEN}"]["per_repo"][rp]), p1(OUT["T3"]["ALL|NEVER"]["per_repo"][rp]),
           str(sum(1 for i in ALL if FX[i]["repo"] == rp))]
    for c in cols:
        rr = OUT["T4"][c]["per_repo"].get(rp)
        row.append("–" if rr is None else p1(rr))
    perrepo[rp] = row
    L.append(f"| {rp} | " + " | ".join(row) + " |")

# ---------------------------------------------------------------- figures
fig, ax = plt.subplots(figsize=(8.5, 6))
items = [(f"{b}", OUT["T4_paired"][f"{b}|H150"]) for b in T4] + \
        [(f"{b} (ALL)", OUT["paired_ALL"][f"{b}|ALL"]) for b in ("NEVER", "TTL100@oracle", "TTL50@oracle", "REPLAY@oracle")]
for k, (lbl, r) in enumerate(items):
    y = len(items) - k
    ax.plot([100 * r["fact"][0], 100 * r["fact"][1]], [y + 0.12] * 2, color="#3b6fb6", lw=2.5, label="fact bootstrap" if k == 0 else None)
    ax.plot([100 * r["clu"][0], 100 * r["clu"][1]], [y - 0.12] * 2, color="#c2452d", lw=2.5, label="repo-cluster bootstrap" if k == 0 else None)
    ax.plot([100 * r["repo_mean_ci"][0], 100 * r["repo_mean_ci"][1]], [y - 0.32] * 2, color="#7a7a7a", lw=1.5, ls=":",
            label="repo-mean (equal weight) CI" if k == 0 else None)
    ax.plot(100 * r["d"], y, "ko", ms=4)
ax.axvline(0, color="k", lw=0.8)
ax.set_yticks(range(len(items), 0, -1)); ax.set_yticklabels([i[0] for i in items], fontsize=8)
ax.set_xlabel("ESM − baseline, served-wrong (pp); negative favours ESM")
ax.set_title("Paired differences: fact-level vs repo-cluster 95 % CIs\n(rows 1–8: H150, real re-derivations; rows 9–12: ALL)", fontsize=10)
ax.legend(fontsize=8, loc="lower left")
fig.tight_layout(); fig.savefig(HERE / "fig_item1_paired.png", dpi=140); plt.close(fig)

fig, ax = plt.subplots(figsize=(8.5, 4.5))
for k, b in enumerate(["REPLAY", "CERT-ZS", "CERT-v0", "LLMDIFF", "TTL50", "TTL100"]):
    per = OUT["T4_paired"][f"{b}|H150"]["per_repo"]
    vals = [100 * v[0] for v in per.values()]
    xs = k + (np.arange(len(vals)) - len(vals) / 2) * 0.03
    ax.scatter(xs, vals, s=14, color="#3b6fb6")
    if "jinja" in per:
        ax.scatter([k], [100 * per["jinja"][0]], s=40, facecolor="none", edgecolor="#c2452d")
    ax.hlines(100 * OUT["T4_paired"][f"{b}|H150"]["repo_mean"], k - 0.3, k + 0.3, color="k")
ax.axhline(0, color="grey", lw=0.8)
ax.set_xticks(range(6)); ax.set_xticklabels(["REPLAY", "CERT-ZS", "CERT-v0h", "LLMDIFF", "TTL50", "TTL100"])
ax.set_ylabel("ESM − baseline per repo (pp)")
ax.set_title("Per-repository paired effects on H150 (dots = repos, bar = equal-weight mean, red ring = jinja)", fontsize=9)
fig.tight_layout(); fig.savefig(HERE / "fig_item1_perrepo.png", dpi=140); plt.close(fig)

(HERE / "item1.md").write_text("\n".join(L), encoding="utf-8")
(HERE / "item1.json").write_text(json.dumps(OUT, indent=1, default=float), encoding="utf-8")
print("\n".join(L))
