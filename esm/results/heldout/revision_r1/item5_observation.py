"""How much of the detector's miss is outside the recorded evidence?
Detection-only records of the frozen ESM detector (DETECT-anchor-hier, ALL 1,419 facts, every commit; stored answer is
always the s0 K, reference evidence always the s0 anchored evidence).  For every read whose stored K is wrong (truth
differs from K) we classify:
  caught            - the detector flagged it (changed / unsure / too large ...)
  blind             - evidence state identical to the s0 reference state (action 'same'): the truth changed outside the
                      recorded evidence; undetectable by construction (observation-completeness violation)
  judge, fresh      - evidence changed, the judge said still_valid on this state (first judgement of the state)
  judge, memo       - evidence changed, a memoised still_valid of the same (anchor, state) was reused
crossed with oracle value NONE (referent vanished: removed / moved path / unparseable) vs present.
Read level and episode level (episode = maximal run of consecutive commits at which K is wrong).
Output: item5.md, item5.json, fig_item5_blind.png."""
import json
from r1_common import *
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

d = records("DETECT-anchor-hier", "every", columns=["iid", "t", "stored_valid", "flagged", "action", "verdict"])
d = d[d.iid.isin(ALL)].sort_values(["iid", "t"]).reset_index(drop=True)
d["none"] = [truth(i, t) == "NONE" for i, t in zip(d.iid, d.t)]
d["slice"] = [FX[i]["slice"] for i in d.iid]
d["type"] = [FX[i]["type"] for i in d.iid]
d["repo"] = [FX[i]["repo"] for i in d.iid]


def cat(r):
    if r.flagged:
        return "caught"
    if r.action == "same":
        return "blind"
    if r.action == "memo":
        return "judge, memo"
    return "judge, fresh"


w = d[~d.stored_valid].copy()
w["cat"] = [cat(r) for r in w.itertuples()]
CATS = ["caught", "blind", "judge, fresh", "judge, memo"]
L, OUT = ["# Item 5 — observation completeness (generated by item5_observation.py)\n"], {}
L.append(f"Records: DETECT-anchor-hier (the frozen ESM detector), ALL {d.iid.nunique()} facts, every commit; {len(d)} reads, of which "
         f"{len(w)} have a wrong stored answer (FF denominator). FF = 1 − caught share.\n")

# ---------------------------------------------------------------- read level
L.append("## 5a. Read level: stored-wrong reads by outcome × oracle NONE / present\n")
L.append("| slice | stored-wrong reads | caught % | missed % (= FF) | of missed: blind (evidence unchanged) % | of missed: judge said still_valid, fresh % | of missed: still_valid via memo % | of missed: oracle NONE % | blind & NONE / blind & present (reads) | judge & NONE / judge & present (reads) |\n|---|---|---|---|---|---|---|---|---|---|")
for nm, sel in (("ALL", w), ("static", w[w.slice == "static"]), ("behaviour", w[w.slice == "behav"]),
                ("natural", w[w.iid.isin(NAT)]), ("without jinja", w[w.repo != "jinja"])):
    c = sel.cat.value_counts()
    miss = sel[sel.cat != "caught"]
    m = miss.cat.value_counts()
    nm_ = len(miss)
    bl = miss[miss.cat == "blind"]; jd = miss[miss.cat != "blind"]
    o = {"n": len(sel), "caught": int(c.get("caught", 0)), "missed": nm_, "blind": int(m.get("blind", 0)), "fresh": int(m.get("judge, fresh", 0)),
         "memo": int(m.get("judge, memo", 0)), "missed_none": int(miss.none.sum()),
         "blind_none": int(bl.none.sum()), "blind_present": int((~bl.none).sum()), "judge_none": int(jd.none.sum()), "judge_present": int((~jd.none).sum()),
         "facts_blind": int(bl.iid.nunique()), "facts_judge": int(jd.iid.nunique())}
    OUT[f"reads|{nm}"] = o
    pc = lambda a, b: f"{100 * a / max(b, 1):.1f}"
    L.append(f"| {nm} | {len(sel)} | {pc(o['caught'], len(sel))} | {pc(nm_, len(sel))} | {pc(o['blind'], nm_)} ({o['facts_blind']} facts) "
             f"| {pc(o['fresh'], nm_)} | {pc(o['memo'], nm_)} | {pc(o['missed_none'], nm_)} | {o['blind_none']} / {o['blind_present']} | {o['judge_none']} / {o['judge_present']} |")

L.append("\n## 5b. Read level by fact type (missed reads only)\n")
L.append("| type | stored-wrong reads | FF % | missed reads | blind % | judge fresh % | judge memo % | missed with oracle NONE % | facts with any blind miss |\n|---|---|---|---|---|---|---|---|---|")
for t in ["T1", "T2", "T3", "T4", "T5", "T6", "T7", "B"]:
    sel = w[w.type == t]
    miss = sel[sel.cat != "caught"]
    m = miss.cat.value_counts()
    nm_ = max(len(miss), 1)
    OUT[f"type|{t}"] = {"n": len(sel), "missed": len(miss), **{k: int(m.get(k, 0)) for k in CATS[1:]}, "none": int(miss.none.sum())}
    L.append(f"| {t} | {len(sel)} | {100 * len(miss) / max(len(sel), 1):.1f} | {len(miss)} | {100 * m.get('blind', 0) / nm_:.1f} | {100 * m.get('judge, fresh', 0) / nm_:.1f} "
             f"| {100 * m.get('judge, memo', 0) / nm_:.1f} | {100 * miss.none.sum() / nm_:.1f} | {miss[miss.cat == 'blind'].iid.nunique()} |")

# ---------------------------------------------------------------- episode level
eps = []
for iid, x in d.groupby("iid", sort=False):
    sv = x.stored_valid.to_numpy(); fl = x.flagged.to_numpy(); ac = x.action.to_numpy(); nn = x.none.to_numpy(); ts = x.t.to_numpy()
    s = None
    for k in range(len(sv) + 1):
        if k < len(sv) and not sv[k] and s is None:
            s = k
        if (k == len(sv) or sv[k]) and s is not None:
            seg = slice(s, k)
            first = "caught at onset" if fl[s] else ("evidence unchanged at onset" if ac[s] == "same" else "evidence changed, judged still_valid at onset")
            caught = bool(fl[seg].any())
            allsame = bool((ac[seg] == "same").all())
            if caught:
                kind = "caught (at some read)"
            elif allsame:
                kind = "never caught: evidence never changed (blind)"
            else:
                kind = "never caught: evidence changed, judge kept still_valid"
            eps.append({"iid": iid, "slice": FX[iid]["slice"], "type": FX[iid]["type"], "start": int(ts[s]), "len": k - s, "onset": first,
                        "kind": kind, "none_onset": bool(nn[s]), "none_frac": float(nn[seg].mean())})
            s = None
E = pd.DataFrame(eps)
L.append(f"\n## 5c. Episode level ({len(E)} stored-wrong episodes = maximal runs of commits where K is wrong; detection only)\n")
L.append("| slice | episodes | caught at some read % | never caught, evidence never changed (blind) % | never caught, judge kept still_valid % | onset: evidence unchanged % | onset with oracle NONE % | reads in never-caught episodes |\n|---|---|---|---|---|---|---|---|")
for nm, sel in (("ALL", E), ("static", E[E.slice == "static"]), ("behaviour", E[E.slice == "behav"])):
    k = sel.kind.value_counts(normalize=True)
    o = {"n": len(sel), **{a: float(k.get(a, 0)) for a in ["caught (at some read)", "never caught: evidence never changed (blind)",
                                                          "never caught: evidence changed, judge kept still_valid"]},
         "onset_unchanged": float((sel.onset == "evidence unchanged at onset").mean()), "onset_none": float(sel.none_onset.mean()),
         "reads_never": int(sel[sel.kind != "caught (at some read)"].len.sum())}
    OUT[f"eps|{nm}"] = o
    L.append(f"| {nm} | {len(sel)} | {100 * o['caught (at some read)']:.1f} | {100 * o['never caught: evidence never changed (blind)']:.1f} "
             f"| {100 * o['never caught: evidence changed, judge kept still_valid']:.1f} | {100 * o['onset_unchanged']:.1f} | {100 * o['onset_none']:.1f} | {o['reads_never']} |")

L.append("\n### Episodes that were never caught, by type and oracle NONE\n")
L.append("| type | episodes | never caught | of which blind | of which judge still_valid | never caught with oracle NONE at onset |\n|---|---|---|---|---|---|")
for t in ["T1", "T2", "T3", "T4", "T5", "T6", "T7", "B"]:
    sel = E[E.type == t]; nc = sel[sel.kind != "caught (at some read)"]
    L.append(f"| {t} | {len(sel)} | {len(nc)} | {(nc.kind == 'never caught: evidence never changed (blind)').sum()} "
             f"| {(nc.kind == 'never caught: evidence changed, judge kept still_valid').sum()} | {int(nc.none_onset.sum())} |")
blind_eps = E[E.kind == "never caught: evidence never changed (blind)"]
L.append("\nBlind episodes (evidence state identical to s0 throughout, truth ≠ K): " +
         "; ".join(f"`{r.iid}` t={r.start} len={r.len} NONE={r.none_onset}" for r in blind_eps.itertuples()) if len(blind_eps) else "\nNo blind episodes.")
OUT["blind_episodes"] = blind_eps.to_dict("records")

# ---------------------------------------------------------------- detector-independent measure from the evidence states
import pickle
ST = pickle.loads((CACHE / "states_s0.pkl").read_bytes())     # produced by states_s0.py (zero LLM, cached observation tables)
d["state"] = [ST[i][t] for i, t in zip(d.iid, d.t)]
d["ref"] = [ST[i][0] for i in d.iid]
agree = float(((d.state == d.ref) == (d.action == "same")).mean())
# states at which K was right somewhere in FUTURE (plus the s0 reference state itself, where K is right by construction)
okstates = {}
for iid, x in d.groupby("iid", sort=False):
    okstates[iid] = set(x.state[x.stored_valid]) | {ST[iid][0]}
d["state_seen_ok"] = [s in okstates[i] for i, s in zip(d.iid, d.state)]
w = w.join(d[["state_seen_ok"]])
L.append(f"\n## 5d. Detector-independent test: is the evidence state of a stored-wrong read identical to a state at which K was right?\n")
L.append(f"Evidence states recomputed from the cached observation tables (states_s0.py); they agree with the recorded "
         f"'same' action on {100 * agree:.3f} % of reads. A stored-wrong read whose evidence state is identical to a state at which K "
         f"was right (at any FUTURE commit, or s0) is an observation-completeness violation: identical recorded evidence, different "
         f"truth — no judge can be right at both. The remaining stored-wrong reads have evidence that differs from every K-right state, "
         f"so a miss there is a judge error (or an indirect cause the judge could not infer from the visible change).\n")
L.append("| slice / type | stored-wrong reads | identical-to-a-K-right-state reads % (facts) | of them caught (by chance, via another state's verdict) | missed reads | missed reads that are evidence-identical % | missed reads with distinct evidence (judge) % |\n|---|---|---|---|---|---|---|")
groups = [("ALL", w), ("static", w[w.slice == "static"]), ("behaviour", w[w.slice == "behav"]), ("natural", w[w.iid.isin(NAT)])] + \
         [(t, w[w.type == t]) for t in ["T1", "T2", "T3", "T4", "T5", "T6", "T7", "B"]]
for nm, sel in groups:
    ii = sel[sel.state_seen_ok]
    miss = sel[sel.cat != "caught"]
    mi = miss[miss.state_seen_ok]
    OUT[f"identical|{nm}"] = {"n": len(sel), "ident": len(ii), "ident_facts": int(ii.iid.nunique()), "ident_caught": int((ii.cat == "caught").sum()),
                              "missed": len(miss), "missed_ident": len(mi)}
    L.append(f"| {nm} | {len(sel)} | {100 * len(ii) / max(len(sel), 1):.2f} ({ii.iid.nunique()}) | {int((ii.cat == 'caught').sum())} | {len(miss)} "
             f"| {100 * len(mi) / max(len(miss), 1):.1f} | {100 * (len(miss) - len(mi)) / max(len(miss), 1):.1f} |")
# episode level with the same test (onset read)
E["onset_ident"] = [bool(d.loc[(d.iid == r.iid) & (d.t == r.start), "state_seen_ok"].iloc[0]) for r in E.itertuples()]
L.append("\nEpisode level (onset read of each stored-wrong episode; detection-only):\n")
L.append("| slice | episodes | onset evidence identical to a K-right state % | never-caught episodes | of which onset evidence-identical |\n|---|---|---|---|---|")
for nm, sel in (("ALL", E), ("static", E[E.slice == "static"]), ("behaviour", E[E.slice == "behav"])):
    nc = sel[sel.kind != "caught (at some read)"]
    OUT[f"eps_ident|{nm}"] = {"n": len(sel), "ident": int(sel.onset_ident.sum()), "never": len(nc), "never_ident": int(nc.onset_ident.sum())}
    L.append(f"| {nm} | {len(sel)} | {100 * sel.onset_ident.mean():.1f} ({int(sel.onset_ident.sum())}) | {len(nc)} | {int(nc.onset_ident.sum())} |")
idf = E[E.onset_ident]
L.append("\nEpisodes whose onset evidence is identical to a K-right state: " + "; ".join(
    f"`{r.iid}` t={r.start} len={r.len} {'caught' if r.kind.startswith('caught') else 'missed'}" for r in idf.itertuples()))

# ---------------------------------------------------------------- figure
fig, ax = plt.subplots(1, 2, figsize=(10, 3.8))
for a, (nm, key) in zip(ax, (("static", "reads|static"), ("behaviour", "reads|behaviour"))):
    o = OUT[key]
    vals = [o["caught"], o["blind"], o["fresh"], o["memo"]]
    lab = ["caught", "blind (evidence\nunchanged)", "judge still_valid\n(fresh)", "judge still_valid\n(memo)"]
    a.bar(range(4), [100 * v / o["n"] for v in vals], color=["#3b6fb6", "#c2452d", "#e0a040", "#e8c27a"])
    a.set_xticks(range(4)); a.set_xticklabels(lab, fontsize=7)
    a.set_ylabel("% of stored-wrong reads"); a.set_title(f"{nm} facts ({o['n']} stored-wrong reads)", fontsize=9)
    for k, v in enumerate(vals):
        a.annotate(f"{100 * v / o['n']:.1f}", (k, 100 * v / o["n"]), ha="center", fontsize=7, xytext=(0, 2), textcoords="offset points")
fig.suptitle("ESM detector, detection only, ALL facts, every commit", fontsize=9)
fig.tight_layout(); fig.savefig(HERE / "fig_item5_blind.png", dpi=140); plt.close(fig)

(HERE / "item5.md").write_text("\n".join(L), encoding="utf-8")
(HERE / "item5.json").write_text(json.dumps(OUT, indent=1, default=lambda o: o.item() if hasattr(o, "item") else str(o)), encoding="utf-8")
print("\n".join(L))
