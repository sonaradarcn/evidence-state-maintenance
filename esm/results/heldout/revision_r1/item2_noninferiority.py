"""Non-inferiority / equivalence (TOST) of ESM against CERT-ZS, CERT-v0h and LLMDIFF.
Δ = ESM − B in served-wrong (pp); positive Δ = ESM worse.
  non-inferiority at margin m (α = 0.05, one-sided): the upper 95 % one-sided bound (95th bootstrap percentile) < m.
  equivalence at margin m (TOST, α = 0.05 each side): the 90 % two-sided interval lies inside (−m, +m).
Bounds from the fact-level bootstrap (paper's unit) and from the repo-cluster bootstrap (B = 2000), and from the
equal-weight repo-level mean (bootstrap over repos).  CERT-v0h is evaluated on its 133 static facts and ESM on exactly
the same 133 facts.  Output: item2.md, item2.json, fig_item2_tost.png."""
import json
from r1_common import *
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

MARGINS = (0.010, 0.015, 0.020, 0.030)
L, OUT = ["# Item 2 — non-inferiority and equivalence (generated by item2_noninferiority.py)\n"], {}

# absolute rates on the common facts
L.append("## 2a. Absolute rates on common denominators (H150, every commit)\n")
L.append("| comparison | common facts | ESM served-wrong % | baseline served-wrong % | ESM tokens/fact | baseline tokens/fact |\n|---|---|---|---|---|---|")
rows = []
for b, sch in (("CERT-ZS", "every"), ("CERT-v0", "every"), ("LLMDIFF", "every"), ("CERT-ZS", "every50"), ("CERT-v0", "every50"),
               ("LLMDIFF", "every50")):
    r = paired_stats(pf(FROZEN, sch), pf(b, sch), H150)
    OUT[f"{b}|{sch}"] = r
    rows.append((b, sch, r))
    L.append(f"| ESM vs {b} ({sch}) | {r['n']} | {p1(r['wa'])} | {p1(r['wb'])} | {r['toka'] / 1000:.1f}k | {r['tokb'] / 1000:.1f}k |")
e = pf(FROZEN)
st133 = sorted(set(pf("CERT-v0").index) & H150)
x = e.loc[st133]
L.append(f"\nESM on the 133 CERT-v0h facts: {p1(x.sw.sum() / x.reads.sum())} % at {x.tok.mean() / 1000:.1f}k tokens/fact "
         f"(on all 160 H150 facts: 6.9 % at 26.5k). The 27 H150 facts not covered by CERT-v0h are the behaviour facts.\n")
OUT["ESM_on_133"] = {"sw": x.sw.sum() / x.reads.sum(), "tok": x.tok.mean(),
                     "slices": dict(pd.Series([FX[i]["slice"] for i in set(H150) - set(st133)]).value_counts())}

L.append("\n## 2b. Bounds and tests (Δ = ESM − B, pp; NI = non-inferior; EQ = equivalent by TOST)\n")
L.append("| comparison | unit | Δ | 95 % CI | 90 % CI | one-sided 95 % upper bound | smallest NI margin | smallest EQ margin | NI at 1.0 / 1.5 / 2.0 / 3.0 pp | EQ at 1.0 / 1.5 / 2.0 / 3.0 pp |\n|---|---|---|---|---|---|---|---|---|---|")
for b, sch, r in rows:
    for unit, q in (("facts", r["fact"]), ("repo clusters", r["clu"]), ("repo-mean (equal weight)", r["repo_mean_ci"])):
        d = r["d"] if unit != "repo-mean (equal weight)" else r["repo_mean"]
        lo95, hi95, lo90, hi90 = q
        ni = ["yes" if hi90 < m else "no" for m in MARGINS]
        eq = ["yes" if (lo90 > -m and hi90 < m) else "no" for m in MARGINS]
        OUT[f"{b}|{sch}|{unit}"] = {"d": d, "ci95": [lo95, hi95], "ci90": [lo90, hi90], "ni_margin": hi90, "eq_margin": max(-lo90, hi90)}
        L.append(f"| ESM − {b} ({sch}, {r['n']} facts) | {unit} | {100 * d:+.2f} | [{100 * lo95:+.2f}, {100 * hi95:+.2f}] "
                 f"| [{100 * lo90:+.2f}, {100 * hi90:+.2f}] | {100 * hi90:+.2f} | {100 * max(hi90, 0):.2f} pp | {100 * max(-lo90, hi90):.2f} pp "
                 f"| {' / '.join(ni)} | {' / '.join(eq)} |")

# figure
fig, ax = plt.subplots(figsize=(8, 3.8))
k = 0
labels = []
for b, sch, r in rows:
    if sch != "every":
        continue
    for unit, q, col in (("facts", r["fact"], "#3b6fb6"), ("repo clusters", r["clu"], "#c2452d")):
        y = -k
        ax.plot([100 * q[2], 100 * q[3]], [y, y], color=col, lw=3)
        ax.plot([100 * q[0], 100 * q[1]], [y, y], color=col, lw=1)
        ax.plot(100 * r["d"], y, "ko", ms=4)
        labels.append(f"ESM − {b.replace('CERT-v0', 'CERT-v0h')} ({unit})")
        k += 1
for m in (1.5, 2.0):
    ax.axvline(m, color="grey", ls="--", lw=0.8); ax.axvline(-m, color="grey", ls="--", lw=0.8)
ax.axvline(0, color="k", lw=0.8)
ax.set_yticks([-i for i in range(k)]); ax.set_yticklabels(labels, fontsize=8)
ax.set_xlabel("Δ served-wrong (pp), thick = 90 % CI (TOST), thin = 95 % CI; dashed = ±1.5 and ±2 pp margins")
ax.set_title("H150, every commit: positive Δ = ESM worse", fontsize=9)
fig.tight_layout(); fig.savefig(HERE / "fig_item2_tost.png", dpi=140); plt.close(fig)

(HERE / "item2.md").write_text("\n".join(L), encoding="utf-8")
(HERE / "item2.json").write_text(json.dumps(OUT, indent=1, default=float), encoding="utf-8")
print("\n".join(L))
