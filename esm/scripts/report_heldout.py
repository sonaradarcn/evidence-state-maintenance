def with_setup(pol, pf):
    base = pol.split("@")[0]
    if base in ("CERT-ZS", "CERT-v0") and "@oracle" not in pol:
        pf = pf.copy()
        add = np.array([SETUP.get((base, i), 0) for i in pf.index], float)
        pf["tok"] = pf.tok + add
        pf["rde"] = pf.tok / pf.dtok
    return pf


def summ(pf, ids=None):
    if ids is not None:
        pf = pf[pf.index.isin(ids)]
    if not len(pf):
        return None
    return M.summary(pf)


def repo_weighted(pf, ids=None, seed=0, nb=1000):
    """served-wrong averaged over repos with equal weight (bootstrap: facts resampled within repo)."""
    if ids is not None:
        pf = pf[pf.index.isin(ids)]
    groups = [g for _, g in pf.groupby("repo")]
    est = np.mean([g.sw.sum() / g.reads.sum() for g in groups])
    rng = np.random.default_rng(seed)
    bs = []
    arrs = [(g.sw.to_numpy(float), g.reads.to_numpy(float)) for g in groups]
    for _ in range(nb):
        v = []
        for sw, rd in arrs:
            ix = rng.integers(0, len(sw), len(sw))
            v.append(sw[ix].sum() / rd[ix].sum())
        bs.append(np.mean(v))
    return est, np.percentile(bs, [2.5, 97.5]).tolist()


