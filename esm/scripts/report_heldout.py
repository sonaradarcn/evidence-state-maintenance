# ------------------------------------------------------------------ taxonomy
def taxonomy(pol, sch="every"):
    d = REC[(REC.policy == pol) & (REC.schedule == sch)].sort_values(["iid", "t"])
    cats, fcats, ex = Counter(), defaultdict(set), defaultdict(list)
    for iid, x in d.groupby("iid"):
        origin, origin_ok = "s0", True
        for r in x.itertuples():
            if r.action in ("repair", "rederive"):
                origin, origin_ok = r.action, bool(r.served_valid)
            if r.served_valid:
                continue
            if not origin_ok and r.action not in ("repair", "rederive"):
                c = f"persisting wrong {origin}"
            elif r.action == "repair":
                c = "wrong in-place repair (accepted new answer wrong)"
            elif r.action == "rederive":
                c = "wrong re-derivation (agent answer wrong)"
            elif r.action == "same":
                c = "missed: evidence state unchanged (change outside the recorded evidence)"
            elif r.action == "memo":
                c = "missed: memoised still_valid reused on a state whose truth differs"
            elif r.action in ("valid", "unsure_fresh"):
                c = f"missed: judge said {r.verdict} on a changed state"
            else:
                c = r.action
            c += " | truth NONE" if FX[iid]["truth"][300 + int(r.t)] == "NONE" else " | truth present"
            cats[c] += 1
            fcats[c].add(iid)
            if len(ex[c]) < 6 and (not ex[c] or ex[c][-1][0] != iid):
                ex[c].append((iid, int(r.t), FX[iid]["K"][:50], str(r.served)[:50], FX[iid]["truth"][300 + int(r.t)][:50], str(getattr(r, "reason", ""))[:160]))
    return cats, fcats, ex


