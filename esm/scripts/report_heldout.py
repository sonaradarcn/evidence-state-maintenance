def line(name, s):
    rep = f"{s['repairs']} ({pct(s['repair_rate'])} %)" if s["repairs"] else "–"
    return (f"| {name} | {s['n']} | {pct(s['sw'])} {ci(s['sw_ci'])} | {pct(s['ff'])} | {pct(s['fs'])} | {pct(s['eps_missed'])} "
            f"| {pct(s['life_kept'])} | {s['tok_per_fact'] / 1000:.1f}k | {s['tok_per_read']:.0f} | {s['rde_sum']:.2f} | {s['calls_per_fact']:.1f} "
            f"| {s['der_per_fact']:.2f} | {rep} | {pct(s['ever_sw_chg'])} |")


def table(title, policies, ids, sch="every", note="", key=None, require_full=False):
    L.append(f"\n### {title}\n")
    if note:
        L.append(note + "\n")
    L.append(HDR)
    res = {}
    for name in policies:
        if (name, sch) not in PF:
            continue
        pf = with_setup(name, PF[(name, sch)])
        idx = ids & set(pf.index)
        if not idx or (require_full and len(idx) < len(ids)):
            continue
        s = summ(pf, idx)
        lab = name if len(idx) == len(ids) else f"{name} (only {len(idx)}/{len(ids)})"
        L.append(line(lab, s))
        res[name] = s
    if key:
        OUT[key] = res
    return res


